export function normalizeSense(s){return s.trim().replace(/（[^）]*）|\([^)]*\)/g,'').replace(/^[\s：:]+|[\s。.!！]+$/g,'').replace(/^(?:使|使得)\s*/,'使').replace(/的$/,'');}
const alias=new Map();for(const [label,...senses]of families)for(const s of senses)alias.set(normalizeSense(s),label);
export function senseTags(word){
 const clean=word.meaning.replace(/(?:phrase|modal|prep|conj|pron|adj|adv|aux|num|art|int|vt|vi|n|v)\./gi,';').replace(/（[^）]*）|\([^)]*\)/g,'');
 const values=clean.split(/[;；，,、\n]+/).map(s=>s.trim()).filter(s=>/[\u3400-\u9fff]/.test(s)&&s.length<=32);
 for(const t of word.tags||[])values.push(t);
 return [...new Set(values)].map(s=>({sense:s,label:alias.get(normalizeSense(s))||s}));
}
export function buildCloud(words){
 const groups=new Map();for(const w of words)for(const {sense,label}of senseTags(w)){
  if(!groups.has(label))groups.set(label,{label,words:new Map(),senses:new Set(),matches:new Map()});const g=groups.get(label);g.words.set(w.id,w);g.senses.add(sense);if(!g.matches.has(w.id))g.matches.set(w.id,new Set());g.matches.get(w.id).add(sense);
 }
 return [...groups.values()].map(g=>({...g,count:g.words.size,words:[...g.words.values()],senses:[...g.senses]})).sort((a,b)=>b.count-a.count||a.label.localeCompare(b.label,'zh-CN'));
}
